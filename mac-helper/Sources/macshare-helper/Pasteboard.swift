// Watches NSPasteboard.changeCount (cheap) so main reads the text only when it changed, and tells
// whether the item is marked concealed/transient by a password manager (nspasteboard.org types).
import Cocoa

final class PasteboardWatch {
  private var timer: Timer?
  private var currentEvery: Double = 0
  private var lastCount = -1     // last count we emitted
  private var seenCount = -1     // count seen on the previous tick (emit once it is stable)
  private var first = true
  private static let privateTypes: Set<String> = [
    "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
  ]

  static func info() -> [String: Any] {
    let pb = NSPasteboard.general
    let types = Set((pb.types ?? []).map { $0.rawValue })
    // remote: an item from another Apple device (Universal Clipboard). Its data is fetched from
    // that device when it is first read, behind macOS's "Pasting from …" dialog (#211), so TwinDesk
    // doesn't read it on its own. Reading the types fetches nothing.
    return ["changeCount": pb.changeCount, "concealed": !types.isDisjoint(with: privateTypes),
            "remote": types.contains("com.apple.is-remote-clipboard")]
  }

  // every is 0.25 while the link is in use and 1 while the phone is idle. A pace
  // change keeps lastCount and first: resetting them would re-emit the current item.
  // Omitted every (mesh sends only on) stays 0.25. Off still stops the timer.
  func set(on: Bool, every: Double = 0.25) {
    let interval: Double = every >= 1 ? 1 : 0.25
    if on && timer != nil && interval == currentEvery { return }
    let paceOnly = on && timer != nil
    timer?.invalidate()
    timer = nil
    if !paceOnly {
      lastCount = -1
      seenCount = -1
      first = true
    }
    currentEvery = interval
    guard on else { return }
    if !paceOnly { check() }
    timer = Timer.scheduledTimer(withTimeInterval: interval, repeats: true) { [weak self] _ in self?.check() }
    timer?.tolerance = interval >= 1 ? 0.2 : 0.05 // macOS may run it with other wakeups
  }

  private func check() {
    // Apps write an item in several steps (clear, declare types, set data); wait until the
    // count is the same on two ticks so the concealed flag is read from the finished item.
    let count = NSPasteboard.general.changeCount
    defer { seenCount = count }
    guard count != lastCount, count == seenCount || lastCount == -1 else { return }
    lastCount = count
    var ev = PasteboardWatch.info()
    ev["event"] = "clipboard"
    ev["initial"] = first // the item that was there when watching started (not a new copy)
    first = false
    emit(ev)
  }
}
